package looping_statements;

public class ForLoop {
	//we use for loop when range is given. range (start and end)
	//for(initialization; condition; inc/dec) {}
	public static void main(String[] args) 
	{
		//generate 1 to 5 numbers using for loop
		for(int p=1; p<=5; p++)
		{
			System.out.println(p);
		}
		//generate 18 to 23 numbers using for loop
		for(int n=18; n<=23; n++)
		{
			System.out.println(n);
		}
		
		//generate 73 to 68 numbers using for loop
		for(int i=73; i>=68; i--)
		{
			System.out.println(i);
		}
		
		
		
	}

	
}

package looping_statements;

public class NestedForLoop2 {

	public static void main(String[] args) 
	{
		
		for(int a=1; a<=2; a++)
		{
			for(int i=5; i<=7; i++)
			{
				System.out.print(i +" ");
			}
			System.out.println();
		}
		
		System.out.println("-----------");
		
		for(int n=1; n<=3; n++)
		{
			for(int k=4; k>=2; k--)
			{
				System.out.print(k+" ");
			}
			System.out.println();
		}
		
		System.out.println("---------------");
		
		
		
		
		
		
		
		
		

	}

}

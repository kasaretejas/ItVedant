package looping_statements;

public class WhileLoop 
{

	public static void main(String[] args) 
	{
		//we use while loop when we dont know the end
		//ex - number guessing game
		//ex - ask password until you get correct password
		
		//while(condition)  {}
		//display 1 to 5 number using while loop
		int i=1;
		while(i<=5)
		{
			System.out.println(i);
			i++;
		}

	}

}

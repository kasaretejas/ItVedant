package operators;

public class Comparision 
{
	public static void main(String[] args) 
	{
		System.out.println(10>2);
		System.out.println(10<2);
		System.out.println(10>=2);
		System.out.println(10<=2);
		System.out.println(10!=2);
		System.out.println(10==2);
		
		System.out.println('A'<'a');
		
		//== operator also used with string, we are going to learn more in string
	}
}

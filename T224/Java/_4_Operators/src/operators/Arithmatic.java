package operators;

public class Arithmatic 
{
public static void main(String[] args) 
	{
		System.out.println(12+2);
		System.out.println(12-2);
		System.out.println(12*2);
		System.out.println(12/2); 
		System.out.println(12%2); //reminder 12/2--> reminder is zero
		
		System.out.println(12/5); //2 
		System.out.println(12.0/5); //2.4
		 
		System.out.println('A'+'a'); //Aa (not correct) 65+97  //162
		
		//System.out.println(true+21);
		
		System.out.println("hi"+"bye");
		System.out.println("hi"+"hi"+"hi"+"hi");
		System.out.println("hi"+5+7);
		System.out.println(5+7+"hi");
	}
}

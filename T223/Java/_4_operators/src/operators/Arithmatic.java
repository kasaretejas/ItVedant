package operators;

public class Arithmatic {

	public static void main(String[] args) 
	{
		System.out.println(10+5);
		System.out.println(10.5+5); //15.5
		System.out.println(10-5);
		System.out.println(10*5);
		System.out.println(10%5);
		System.out.println(10/5); //2
		System.out.println(10.0/5); //2.0
		System.out.println(10/3); //3
		System.out.println(10.0/3); //3.33333
		
		//System.out.println(true + 3);
		System.out.println('a'+5); // ASCII a is 97, therefore 97+5=102
		
		System.out.println("hi"+5); //hi5 : concatination/join
		System.out.println(5+"hi"+5);  //5hi5
		System.out.println(5+5+"hi"+5);  //10hi5
		

	}

}

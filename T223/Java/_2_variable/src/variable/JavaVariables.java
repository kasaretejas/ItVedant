package variable;

public class JavaVariables {

	public static void main(String[] args) {
		//variables are used to store data
		//in java, variables are defined as - 
				//datatype variableName; -------> variable declaration
				//variableName = value;  -------> variable initialization
							//OR
				//datatype variableName = value;  ------> variable declaration and initialization in one step
		//example
		int x;
		x=10;
		
		int y;
		//y=45.98;   // invalid data for y (excepted int, got double)
		
		//displaying data in java
		System.out.println("Hello"); //-----> this line will display hello on console
		System.out.println(x);      //------> this line will display value inside variable x
		

	}

}
